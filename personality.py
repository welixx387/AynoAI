# ---------------------------------------------------------------------------
# Простой защитный слой поверх системного промта (пункт C).
# Локальные модели не всегда идеально следуют инструкциям в system-промте,
# поэтому дублируем проверку на уровне кода: если в сообщении пользователя
# встречаются кризисные маркеры, приложение показывает готовый ответ с
# реальной помощью НАПРЯМУЮ, не дожидаясь ответа модели.
# ---------------------------------------------------------------------------
CRISIS_KEYWORDS = [
    "суицид", "покончить с собой", "не хочу жить", "хочу умереть",
    "хочу умереть", "причинить себе вред", "самоповрежд", "убить себя",
    "нет смысла жить", "лучше бы я умер",
    "suicide", "kill myself", "want to die", "self harm", "self-harm",
    "end my life", "don't want to live",
]

CRISIS_RESPONSE = f"""Я на секунду выхожу из роли {PERSONA_NAME} — то, что ты написал(а),
звучит серьёзно, и мне важно ответить тебе честно, как есть.

Если сейчас тебе тяжело и приходят мысли о том, чтобы навредить себе — пожалуйста,
не оставайся с этим один на один. Это можно и нужно обсудить с живым человеком,
который умеет с этим работать:

• Россия — бесплатная круглосуточная линия психологической помощи: 8-800-2000-122
• Если есть угроза жизни прямо сейчас — звони 112 (единая служба экстренной помощи)
• Если ты не в России — попробуй найти в поиске "телефон доверия" или
  "suicide crisis line" + название твоей страны — такие линии почти везде бесплатны
  и работают анонимно

Я — программа, ролевой персонаж, и не могу заменить живого специалиста в такой
ситуации. Но я готов(а) просто поговорить, если тебе сейчас это нужно.
"""


def contains_crisis_signal(text: str) -> bool:
    """Грубая проверка по ключевым словам — дополнительная подстраховка к system-промту."""
    lowered = text.lower()
    return any(keyword in lowered for keyword in CRISIS_KEYWORDS)
